"""Annotate each term occurrence with a verdict (CONFORME / error code / VAR_J / VAR_NJ).

Reads occurrence files in the TermJudge input format
(``<input-dir>/<SYSTEM>/<DOC>.json``, see ``docs/input_format.md``), applies
the decision tree of the metric, and writes one annotation JSON per
(system, document) under ``<output-dir>/<SYSTEM>/runs/<run_tag>/annotations/``.

No numeric score is computed here: see :mod:`termjudge.metric.score`.

CLI::

    termjudge-annotate \\
        --input-dir <dir> --glossary <glossary.csv> --systems sys1,sys2 \\
        --source-docs-dir <dir> --target-docs-dir <dir> --context-window 5 \\
        --reference-mode validated --q1-mode llm --q2-mode llm \\
        --model gpt-4.1-mini --output-dir <out>
"""

