def concept_key_of(record: dict) -> str:
    """Stable concept identifier: normalised English head term (falls back to
    the source form when the record carries no head term)."""
    term = io_records.head_term(record) or record.get("source_term") or ""
    return term.strip().lower()


def _reading_order(records: List[dict]):
    """``(index, record)`` pairs sorted by segment id, ties kept in file order."""
    return sorted(enumerate(records), key=lambda kv: tuple(kv[1].get("source_segment_ids") or ()))


def propagation_key(record: dict):
    """Grouping key of the IDENTICAL occurrences for ``--propagate-q1``.

    ``(concept, source lemma, normalised raw target)``. The source form is taken
    at the LEMMA (same key as everywhere else in the metric, so the group
    necessarily shares the same R(s)); the target is taken RAW and only
    normalised (case, whitespace, edge punctuation, articles), NOT lemmatised:
    lemmatising would merge singular and plural, i.e. precisely where
    agreement errors live.

    Returns ``None`` when the record has no concept or no usable source form
    (it is then judged alone).
    """
    ckey = concept_key_of(record)
    src = normalise(io_records.source_lemma(record))
    if not ckey or not src:
        return None
    return (ckey, src, normalise(io_records.raw_target(record)))


def pick_representative(indices: List[int], policy: str, seed_key: tuple) -> int:
    """Occurrence of a group that carries the propagated Q1 judgment.

    ``indices`` is in reading order. ``random`` is a DETERMINISTIC draw (a
    stable hash of ``seed_key``, not ``hash()`` which is salted per process):
    two runs of the same configuration pick the same representative, otherwise
    the LLM cache and the comparison between runs would lose all meaning.
    """
    if not indices:
        raise ValueError("pick_representative: empty group")
    if policy == "first":
        return indices[0]
    if policy == "second":
        return indices[1] if len(indices) > 1 else indices[0]
    if policy == "random":
        import hashlib
        digest = hashlib.sha1("\x1f".join(str(x) for x in seed_key).encode("utf-8")).digest()
        return indices[int.from_bytes(digest[:8], "big") % len(indices)]
    return indices[-1]   # "last" (default)


def build_concept_chain(records: List[dict], current_idx: int, tgt_getter) -> str:
    """All OTHER occurrences of the same concept in the doc (both prior and
    subsequent). Used by the hapax judge: the hapax has no chain of its own
    source form, but other source forms of its concept provide evidence.
    """
    cur_key = concept_key_of(records[current_idx])
    if not cur_key:
        return ""
    lines: List[str] = []
    for i, r in _reading_order(records):
        if i == current_idx or concept_key_of(r) != cur_key:
            continue
        lines.append(f"  - {r.get('source_term', '')} -> {tgt_getter(r)!r}")
    return "\n".join(lines)


def build_concept_history(records: List[dict], current_idx: int, tgt_getter) -> Tuple[bool, str]:
    cur_key = concept_key_of(records[current_idx])
    if not cur_key:
        return True, ""
    positions = [i for i, r in _reading_order(records) if concept_key_of(r) == cur_key]
    try:
        rank = positions.index(current_idx)
    except ValueError:
        rank = 0
    is_first = rank == 0
    history_lines: List[str] = []
    for i in positions[:rank]:
        r = records[i]
        history_lines.append(f"  - {r.get('source_term', '')} -> {tgt_getter(r)!r}")
    return is_first, "\n".join(history_lines)


def build_concept_history_grouped(records: List[dict], current_idx: int, tgt_getter) -> Tuple[bool, str]:
    """Prior renderings of the concept GROUPED by (source form, rendering),
    with counts, instead of one line per occurrence::

        - "slow slip" -> "glissement lent" (×15)
        - "aseismic slip" -> "glissement asismique" (×4) ; -> "glissement aseismique" (×2)

    Forms sorted by decreasing total count; for one form, renderings by
    decreasing count (order of appearance on ties). Grouping is
    case-insensitive (the first spelling met is displayed)."""
    cur_key = concept_key_of(records[current_idx])
    if not cur_key:
        return True, ""
    positions = [i for i, r in _reading_order(records) if concept_key_of(r) == cur_key]
    try:
        rank = positions.index(current_idx)
    except ValueError:
        rank = 0
    # {form_key: (displayed spelling, {rendering_key: [spelling, count]})}, orders preserved
    forms: Dict[str, Tuple[str, Dict[str, List]]] = {}
    for i in positions[:rank]:
        r = records[i]
        src = (r.get("source_term") or "").strip()
        tgt = str(tgt_getter(r)).strip()
        fk, tk = src.lower(), tgt.lower()
        if fk not in forms:
            forms[fk] = (src, {})
        rend = forms[fk][1]
        if tk not in rend:
            rend[tk] = [tgt, 0]
        rend[tk][1] += 1
    lines = []
    for _, (src_disp, rend) in sorted(forms.items(), key=lambda kv: -sum(v[1] for v in kv[1][1].values())):
        parts = sorted(rend.values(), key=lambda v: -v[1])
        cells = [f'"{src_disp}" -> "{parts[0][0]}" (×{parts[0][1]})']
        cells += [f'-> "{t}" (×{n})' for t, n in parts[1:]]
        lines.append("- " + " ; ".join(cells))
    return rank == 0, "\n".join(lines)


def build_concept_renderings(records: List[dict], current_idx: int, tgt_getter) -> str:
    """``{concept_renderings}`` block of the Q2 prompt: the renderings of the
    concept OBSERVED SO FAR, grouped by source form, each form labelled
    head term / variant, the evaluated form marked, with counts and first
    segment::

        Renderings of this concept so far in this document, grouped by source form:
        - "slow slip" (HEAD TERM — the form under evaluation): "glissement lent" (×12, first at seg 4)
        - "aseismic slip" (variant): "glissement asismique" (×4)

    Evaluated form first (with ``first at seg`` on its renderings), then the
    others by decreasing total count. Block ends with a blank line; ``""`` when
    there is no prior rendering (first mention)."""
    r_cur = records[current_idx]
    cur_key = concept_key_of(r_cur)
    if not cur_key:
        return ""
    head_key = io_records.head_term(r_cur).lower()
    cur_form_key = (r_cur.get("source_term") or "").strip().lower()
    positions = [i for i, r in _reading_order(records) if concept_key_of(r) == cur_key]
    try:
        rank = positions.index(current_idx)
    except ValueError:
        rank = 0
    # {form_key: [spelling, {rendering_key: [spelling, count, first_seg]}]}
    forms: Dict[str, List] = {}
    for i in positions[:rank]:
        r = records[i]
        src = (r.get("source_term") or "").strip()
        tgt = str(tgt_getter(r)).strip()
        seg = (r.get("source_segment_ids") or [None])[0]
        fk, tk = src.lower(), tgt.lower()
        if fk not in forms:
            forms[fk] = [src, {}]
        rend = forms[fk][1]
        if tk not in rend:
            rend[tk] = [tgt, 0, seg]
        rend[tk][1] += 1
    if not forms:
        return ""

    def _form_line(fk: str) -> str:
        src_disp, rend = forms[fk]
        is_cur = fk == cur_form_key
        role = "HEAD TERM" if (head_key and fk == head_key) else "variant"
        if is_cur:
            role += " — the form under evaluation"
        parts = sorted(rend.values(), key=lambda v: -v[1])
        # "dominant": the top rendering is STRICTLY more frequent than the
        # second one (a single rendering is dominant; a tie at the top means
        # no dominant rendering, the form has no established usage).
        # Referenced by rule 2 of the Q2 prompt.
        dom = len(parts) == 1 or parts[0][1] > parts[1][1]
        cells = []
        for i, (tgt_disp, n, seg) in enumerate(parts):
            tags = [f"×{n}"]
            if dom and i == 0:
                tags.append("dominant")
            if is_cur and seg is not None:
                tags.append(f"first at seg {seg}")
            cells.append(f'"{tgt_disp}" ({", ".join(tags)})')
        return f'- "{src_disp}" ({role}): ' + " ; ".join(cells)

    keys = sorted(forms, key=lambda fk: -sum(v[1] for v in forms[fk][1].values()))
    keys = ([cur_form_key] if cur_form_key in forms else []) + [k for k in keys if k != cur_form_key]
    lines = [_form_line(fk) for fk in keys]
    return ("Renderings of this concept so far in this document, grouped by source form:\n"
            + "\n".join(lines) + "\n\n")


def other_form_references(
    concept_key: str,
    current_src_norm: str,
    references: Dict[Tuple[str, str], ReferenceChoice],
) -> Dict[str, str]:
    out: Dict[str, str] = {}
    for (ckey, src_norm), ref in references.items():
        if ckey != concept_key or src_norm == current_src_norm:
            continue
        if ref.reference:
            out[src_norm] = ref.reference
    return out


def load_prompts() -> Dict[str, str]:
    """Load the prompt templates (``prompts/<name>.txt``).

    The hapax judge reuses the text of ``q1_classify``: judging a hapax or
    validating a pseudo-reference is judging an alignment, with the same
    typology, procedure and output schema. The alias guarantees the identity
    by construction (no copy to keep in sync when Q1 is edited).
    """
    prompts = {
        name: (PROMPTS_DIR / f"{name}.txt").read_text(encoding="utf-8")
        for name in PROMPT_NAMES
    }
    prompts["hapax_judge"] = prompts["q1_classify"]
    return prompts


def build_examples_block(name: str) -> str:
    """Build the few-shot block of one prompt from its examples file.

    Reads ``prompts/<name>.examples.txt`` when it exists. Two formats are
    accepted:
    - ``@@@`` separators: a preamble, then examples separated by lines of ``@@@``.
    - ``<example>...</example>`` blocks: a preamble, then one such block per
      example. An optional ``<examples>...</examples>`` wrapper around the
      whole file is honoured and rebuilt around the output.

    Returns the preamble plus the examples, or an empty string when the file
    does not exist or has no examples.
    """
    path = PROMPTS_DIR / f"{name}.examples.txt"
    if not path.exists():
        return ""
    text = path.read_text(encoding="utf-8")
    wrapper = False
    if "\n@@@\n" in text:
        parts = text.split("\n@@@\n")
        preamble = parts[0].strip("\n")
        examples = [p.strip("\n") for p in parts[1:] if p.strip()]
    elif "<example>" in text:
        wrapper = "<examples>" in text
        body = re.sub(r"</?examples>", "", text)  # strip the outer wrapper (keeps <example>)
        cut = body.find("<example>")
        preamble = body[:cut].strip()
        examples = [m.group(0).strip() for m in re.finditer(r"<example>.*?</example>", body, re.S)]
    else:  # single unstructured example / whole file
        preamble, examples = text.strip("\n"), []
    if not examples:
        return ""
    block = (preamble + "\n\n" if preamble else "") + "\n\n".join(examples)
    if wrapper:
        # Trailing blank line so the following section is cleanly separated
        # while the template keeps {examples_block} glued to the next token:
        # that way an empty block leaves no dangling blank lines.
        block = f"<examples>\n{block}\n</examples>\n\n"
    return block


def inject_examples(prompts: Dict[str, str]) -> Dict[str, str]:
    """Substitute the static ``{examples_block}`` token of each template with
    the few-shot examples read from its examples file (an empty string when
    the template has none). The examples keep their doubled ``{{ }}`` braces so
    the later per-occurrence ``str.format`` renders them as literal JSON.
    """
    return {
        name: tmpl.replace("{examples_block}", build_examples_block(name))
        for name, tmpl in prompts.items()
    }


def inject_domain(prompts: Dict[str, str], domain: str) -> Dict[str, str]:
    """Substitute the static ``{domain}`` token in every template with the bare
    domain name (e.g. ``biomedical``), woven inline in sentences such as
    "in the {domain} domain". Falls back to "specialised" when the domain is
    empty so the sentence stays grammatical. Braces in the injected text are
    escaped so it survives the later per-occurrence ``str.format()``.
    """
    bare = ((domain or "").strip() or "specialised").replace("{", "{{").replace("}", "}}")
    return {name: tmpl.replace("{domain}", bare) for name, tmpl in prompts.items()}


_SAFE_TAG = re.compile(r"[^\w.+=-]+")


def _safe_for_path(s: str) -> str:
    return _SAFE_TAG.sub("-", s).strip("-_") or "x"


def build_run_tag(args) -> str:
    """Generate a deterministic, human-readable folder name from the run config.

    Two runs with the same configuration produce the same tag; two runs with
    any differing option produce different tags. The tag is used as a
    subfolder under ``<output>/<SYSTEM>/runs/<tag>/`` so that results from
    different configurations never overwrite each other.
    """
    parts = [
        f"ref-{_safe_for_path(args.reference_mode)}",
        f"q1-{args.q1_mode}",
        *([f"gen-{args.generate_scope}-c{args.generate_contexts}"]
          if "generate" in (args.reference_mode or "") else []),
        f"dom-{_safe_for_path(args.domain or 'none')}",
        f"q2-{args.q2_mode}",
        f"hapax-{args.hapax_mode}",
        *([f"path-{args.judge_path}"] if args.judge_path != "auto" else []),
        *([f"prop-{args.propagate_pick}"] if args.propagate_q1 != "off" else []),
        f"sc-{args.llm_shortcuts}",
        f"ctx{args.context_window}",
        _safe_for_path(args.model),
    ]
    return "__".join(parts)


def make_dump_label(system: str, record: dict) -> str:
    """Build a human-readable label for prompt dumps.

    Example: ``sysA_doc12_seg7_the-list-experiment``. Used to name the saved
    prompt markdown files so they can be located later by inspection of the
    chains (system + doc + segment + source form).
    """
    seg = record.get("source_segment_ids") or [None]
    seg0 = seg[0] if seg else "?"
    src_form = record.get("source_term") or "?"
    return f"{system}_{record.get('doc_id', '?')}_seg{seg0}_{src_form}"


def is_vedette(record: dict, entry) -> bool:
    """True if the source form IS the concept's prefLabel_en (the head term)."""
    if entry is None or not entry.preflabel_en:
        return False
    form = (record.get("source_term") or "").strip().lower()
    return form == entry.preflabel_en.strip().lower()


def lookup_glossary(glossary: Optional[Glossary], record: dict):
    """Lookup by record ``term_id`` (matches glossary ``tid``), with a fallback
    on the English head term (or source form) among prefLabel and altLabel."""
    if glossary is None:
        return None
    tid = record.get("term_id")
    if isinstance(tid, int):
        hit = glossary.get(tid)
        if hit is not None:
            return hit
    return glossary.get_by_name(concept_key_of(record))


