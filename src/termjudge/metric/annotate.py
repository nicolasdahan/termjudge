def annotate_doc(
    *,
    system: str,
    doc_id: str,
    records: List[dict],
    args: argparse.Namespace,
    glossary: Optional[Glossary],
    chain: List[str],
    llm: Optional[LLMClient],
    prompts: Dict[str, str],
    context_loader: Optional[ContextLoader],
) -> Tuple[List[OccurrenceAnnotation], List[dict]]:
    """Annotate one (system, doc). Returns ``(annotations, generation_traces)``;
    the traces (one per (concept, form) where the ``generate`` strategy was
    attempted) are persisted by the caller for human audit."""
    records_by_system = {system: records}
    observations = collect_observations(
        records_by_system,
        source_key=io_records.source_lemma,
        canonical_tgt=io_records.canonical_target,
        target_lemma=io_records.target_lemma,
        concept_key=concept_key_of,
        raw_target=io_records.raw_target,
    )

    references: Dict[Tuple[str, str], ReferenceChoice] = {}
    for (ckey, src_norm), obs_list in observations.items():
        group = [r for i, r in _reading_order(records)
                 if concept_key_of(r) == ckey
                 and normalise(io_records.source_lemma(r)) == src_norm]
        matching = group[0] if group else None
        glossary_entry = lookup_glossary(glossary, matching) if matching else None
        src_form = io_records.canonical_source(matching) if matching else ""
        # Head-term gate for the glossary reference: the source form is the
        # head term either when its variation category is 'no_variation', or
        # when it equals the glossary prefLabel_en. Variants fall back to
        # frequency/first.
        is_ved = bool(matching) and (
            (matching.get("variation_category") or "").strip() == "no_variation"
            or is_vedette(matching, glossary_entry)
        )
        # SOURCE-side contexts (EN) for the "generate" strategy, in reading
        # order and deduped per segment. Source text is identical across MT
        # systems, so the generation prompt (hence its cache entry) is shared.
        contexts: List[Tuple[object, str]] = []
        seen_ctx = set()
        for r in group:
            seg = r.get("source_segment_ids") or []
            seg0 = seg[0] if seg else None
            txt = (r.get("source_segment") or "").strip()
            k = (seg0, txt)
            if txt and k not in seen_ctx:
                seen_ctx.add(k)
                contexts.append((seg0, txt))
        # Validation of a pseudo-reference: it comes from a specific
        # OCCURRENCE, so it is judged as Q1 judges any alignment: on its source
        # segment AND its translation, with the same supporting blocks. The
        # callback finds the representative occurrence (first of the group, in
        # reading order, whose target lemma is the one retained: the
        # `first_seen` of _candidates) and renders the blocks like the Q1 call site.
        def _validation_evidence(target_lemma: str, _group=group) -> Optional[dict]:
            rep = next((r for r in _group
                        if io_records.target_lemma(r) == target_lemma), None)
            if rep is None:
                rep = next((r for r in _group if io_records.target_lemma(r)), None)
            if rep is None:
                return None
            r_idx = next((i for i, x in enumerate(records) if x is rep), None)
            if r_idx is None:
                return None
            _, hist_indexed = build_concept_history_grouped(records, r_idx, io_records.raw_target)
            pairs = ""
            if args.context_window > 0 and context_loader is not None:
                pairs = context_loader.context_window_pairs(
                    doc_id=doc_id,
                    system=system,
                    src_sent_ids=rep.get("source_segment_ids") or [],
                    tgt_sent_ids=io_records.target_segment_ids(rep),
                    n=args.context_window,
                )
            return {
                "src_segment": rep.get("source_segment", "") or "",
                "tgt_segment": rep.get("target_segment", "") or "",
                "tgt_aligned_raw": io_records.raw_target(rep),
                "src_form_raw": rep.get("source_term") or src_form,
                "context_pairs": pairs,
                "concept_history_indexed": hist_indexed,
            }

        retry_t = args.generate_retry_temperature
        rc = select_reference(
            chain=chain,
            src_form=src_form,
            glossary_entry=glossary_entry,
            doc_id=doc_id,
            observations=obs_list,
            llm=llm if ("llm" in chain or "generate" in chain or "validated" in chain) else None,
            llm_prompt_tmpl=prompts.get("select_reference") if "llm" in chain else None,
            is_vedette=is_ved,
            generate_prompt_tmpl=prompts.get("generate_reference") if ("generate" in chain or "validated" in chain) else None,
            variation_category=(matching.get("variation_category") or "") if matching else "",
            source_contexts=contexts,
            generate_scope=args.generate_scope,
            generate_contexts=args.generate_contexts,
            generate_retry_temperature=None if (retry_t is not None and retry_t < 0) else retry_t,
            # Reference validation in context: the prompt is the Q1 one (alias
            # hapax_judge), so its system message and its cache family are those
            # of Q1. The text produced is then the same as for a Q1 judgment of
            # that occurrence, so the call can be served by the Q1 cache. The
            # dumps stay isolated (dump_name).
            hapax_prompt_tmpl=prompts.get("hapax_judge") if "validated" in chain else None,
            validation_evidence=_validation_evidence if "validated" in chain else None,
            hapax_validate_system=Q1_SYSTEM if "validated" in chain else None,
            hapax_validate_prompt_name="q1_classify" if "validated" in chain else "hapax_judge",
        )
        if rc.generation_trace is not None:
            rc.generation_trace.setdefault("concept", ckey)
        references[(ckey, src_norm)] = rc

    # Chain size per (concept, src_form): used for hapax detection
    chain_sizes = {key: len(obs_list) for key, obs_list in observations.items()}

    # --propagate-q1: groups of IDENTICAL occurrences of this document, and
    # the occurrence designated to carry the Q1 judgment of each group.
    # A group of size >= 2 implies a (concept, form) chain of size >= 2, so NO
    # hapax ever enters a propagated group. All the occurrences of a group
    # share the same R(s) and the same target, hence the same match_level:
    # they are routed identically (all to Q1, or all short-circuited). The memo
    # is therefore never filled for a group that does not reach Q1.
    _prop_on = args.propagate_q1 == "on"
    _prop_groups: Dict[tuple, List[int]] = {}
    _prop_rep: Dict[tuple, int] = {}
    if _prop_on:
        for _i, _rec in enumerate(records):
            _k = propagation_key(_rec)
            if _k is not None:
                _prop_groups.setdefault(_k, []).append(_i)
        for _k, _idxs in _prop_groups.items():
            _idxs.sort(key=lambda i: (tuple(records[i].get("source_segment_ids") or ()), i))
            _prop_rep[_k] = pick_representative(_idxs, args.propagate_pick, (doc_id,) + _k)
    _q1_memo: Dict[tuple, object] = {}

    def _q1_call(rec: dict, rec_idx: int):
        """One Q1 call for the occurrence ``rec`` (index ``rec_idx`` in
        ``records``). ALL the blocks of the prompt are rebuilt from this
        occurrence (current segment, context window, concept history,
        provenance of R(s)), so that a propagated verdict is exactly the one
        the representative occurrence would have produced, and the path
        without propagation stays identical to the per-occurrence behaviour.
        """
        r_src_raw = io_records.canonical_source(rec)
        r_src_norm = normalise(io_records.source_lemma(rec))
        r_ref = references.get((concept_key_of(rec), r_src_norm))
        r_level = match_level(io_records.target_lemma(rec),
                              r_ref.reference_lemma if r_ref else "")
        r_gloss = lookup_glossary(glossary, rec)
        _, r_history = build_concept_history(records, rec_idx, io_records.raw_target)
        _, r_history_indexed = build_concept_history_grouped(records, rec_idx, io_records.raw_target)
        r_ctx_window = ""
        r_ctx_pairs = ""
        if args.context_window > 0 and context_loader is not None:
            _kw = dict(
                doc_id=doc_id,
                system=system,
                src_sent_ids=rec.get("source_segment_ids") or [],
                tgt_sent_ids=io_records.target_segment_ids(rec),
                n=args.context_window,
            )
            r_ctx_window = context_loader.context_window(**_kw)
            r_ctx_pairs = context_loader.context_window_pairs(**_kw)
        return q1_classify(
            llm=llm,
            prompt_tmpl=prompts["q1_classify"],
            src_segment=rec.get("source_segment", ""),
            tgt_segment=rec.get("target_segment", ""),
            src_form_raw=(rec.get("source_term") or r_src_raw),
            tgt_aligned_raw=io_records.raw_target(rec),
            src_canonical=r_src_raw,
            tgt_canonical=io_records.canonical_target(rec),
            reference=r_ref.reference if r_ref else "",
            variation_category=rec.get("variation_category", "") or "",
            concept_history=r_history,
            context_window=r_ctx_window,
            concept_preflabel_fr=(r_gloss.preflabel_fr if r_gloss else ""),
            dump_label=make_dump_label(system, rec),
            # Provenance of R(s) + relation to the target: the anchoring of the
            # prompt depends on it. See q1.build_evidence_block.
            reference_source=(r_ref.source if r_ref else ""),
            match_level=r_level,
            validated_refs=("validated" in chain),
            concept_preflabel_en=(r_gloss.preflabel_en if r_gloss else ""),
            # Paired EN/FR preceding segments + grouped history.
            context_pairs=r_ctx_pairs,
            concept_history_indexed=r_history_indexed,
        )

    annotations: List[OccurrenceAnnotation] = []
    show_inner = (
        args.progress
        and (args.q1_mode == "llm" or args.q2_mode == "llm")
        and not args.dry_run
        and args.workers <= 1   # avoid tangled nested bars under parallelism
    )
    inner_iter = _maybe_tqdm(
        list(enumerate(records)),
        enabled=show_inner,
        desc=f"  {doc_id}",
        unit="occ",
        leave=False,
    )
    # --judge-path q1q2: EVERYTHING goes through Q1 -> Q2 (hapax included), so
    # the whole verdict space is reachable (Q1 -> error codes, Q2 -> VAR_NJ).
    # "auto" -> normal routing.
    _force_q1q2 = args.judge_path == "q1q2"

    for idx, r in inner_iter:
        ckey = concept_key_of(r)
        if not ckey:
            continue
        src_raw = io_records.canonical_source(r)      # natural (display / prompt)
        src_key = io_records.source_lemma(r)          # lemma (grouping key)
        if not src_key:
            continue
        src_norm = normalise(src_key)
        ref_choice = references.get((ckey, src_norm))
        if ref_choice is None:
            continue
        # ref_choice.reference may be "" when this source form was NEVER translated
        # in the document (only non-translations). We do NOT skip those: with an
        # empty target the match is "none" (a divergence), so the occurrence flows
        # to Q1 / the hapax judge and the LLM decides: an error if the term should
        # have been translated, or NO (justified omission) -> Q2. Skipping would
        # silently drop both the real errors AND the legitimate cases.
        tgt = io_records.canonical_target(r)          # natural (display / q2)
        tgt_lemma = io_records.target_lemma(r)        # lemma (match)
        level = match_level(tgt_lemma, ref_choice.reference_lemma)

        glossary_entry = lookup_glossary(glossary, r)
        term_id_record = r.get("term_id", -1)
        is_first, history = build_concept_history(records, idx, io_records.raw_target)
        # Prior renderings GROUPED with counts.
        _, history_indexed = build_concept_history_grouped(records, idx, io_records.raw_target)
        ctx_window = ""
        ctx_pairs = ""
        if args.context_window > 0 and context_loader is not None:
            _ctx_kw = dict(
                doc_id=doc_id,
                system=system,
                src_sent_ids=r.get("source_segment_ids") or [],
                tgt_sent_ids=io_records.target_segment_ids(r),
                n=args.context_window,
            )
            ctx_window = context_loader.context_window(**_ctx_kw)
            ctx_pairs = context_loader.context_window_pairs(**_ctx_kw)

        tgt_aligned_raw_val = io_records.raw_target(r)
        is_hapax = chain_sizes.get((ckey, src_norm), 0) == 1
        common = dict(
            system=system,
            doc_id=r.get("doc_id", ""),
            term_id=int(term_id_record) if isinstance(term_id_record, int) else -1,
            concept_key=ckey,
            source_term=r.get("source_term", src_raw),
            target_canonical=tgt,
            target_term=tgt_aligned_raw_val,
            reference=ref_choice.reference,
            reference_source=ref_choice.source,
            reference_confidence=ref_choice.confidence,
            match_level=level,
            is_first_mention=is_first,
            variation_category=r.get("variation_category", "") or "",
            source_segment_ids=list(r.get("source_segment_ids") or []),
            concept_preflabel_en=glossary_entry.preflabel_en if glossary_entry else "",
            concept_preflabel_fr=glossary_entry.preflabel_fr if glossary_entry else "",
            is_hapax=is_hapax,
        )

        # Hapax routing: ALL hapax go through the hapax judge, regardless of
        # whether the source form is in the glossary. The judge accepts an
        # optional reference: if R(s) exists (e.g. from glossary or frequency),
        # the LLM uses it as the expected translation; otherwise it judges on
        # the merits of the concept chain.
        #
        # Routing is BEFORE the exact-match shortcut because for hapax without
        # a usable reference the match would be trivially exact (target IS the
        # reference via the frequency fallback): we would lose the evaluation.
        #
        # --judge-path q1q2 disables this whole branch: hapax then fall through
        # to the shared Q1 -> Q2 path like any other alignment.
        if is_hapax and not _force_q1q2:
            if args.hapax_mode == "skip":
                annotations.append(OccurrenceAnnotation(verdict="SKIPPED_HAPAX", **common))
                continue
            # Shortcut: trusted exact match for a hapax head term in the glossary.
            if (
                args.llm_shortcuts == "non_hapax_and_vedette"
                and level in ("exact", "graphic")
                and ref_choice.source == "glossary"
                and is_vedette(r, glossary_entry)
            ):
                annotations.append(OccurrenceAnnotation(verdict="CONFORME", **common))
                continue
            if not args.dry_run and llm is not None:
                concept_chain = build_concept_chain(records, idx, io_records.raw_target)
                # Pass R(s) only when it differs from the target itself (otherwise
                # a degenerate frequency=self fallback).
                hapax_reference = ref_choice.reference if (
                    ref_choice.reference
                    and normalise(ref_choice.reference) != normalise(tgt)
                ) else None
                hr = hapax_judge(
                    llm=llm,
                    prompt_tmpl=prompts["hapax_judge"],
                    src_segment=r.get("source_segment", ""),
                    tgt_segment=r.get("target_segment", ""),
                    # source_term = surface form (case preserved), shown to the
                    # LLM as it appears in the segment. Consistent with the raw
                    # target and the concept history/chain.
                    src_form_raw=(r.get("source_term") or src_raw),
                    tgt_aligned_raw=tgt_aligned_raw_val,
                    src_canonical=src_raw,
                    tgt_canonical=tgt,
                    concept_preflabel_en=common["concept_preflabel_en"],
                    concept_preflabel_fr=common["concept_preflabel_fr"],
                    variation_category=common["variation_category"],
                    concept_chain=concept_chain,
                    reference=hapax_reference,
                    context_window=ctx_window,
                    dump_label=make_dump_label(system, r),
                )
                verdict = "CONFORME" if hr.code == "NO" else hr.code
                annotations.append(OccurrenceAnnotation(
                    verdict=verdict,
                    hapax_code=hr.code,
                    hapax_justification=hr.justification,
                    **common,
                ))
                continue
            # dry-run on a hapax -> SKIPPED_HAPAX (no LLM available)
            annotations.append(OccurrenceAnnotation(verdict="SKIPPED_HAPAX", **common))
            continue

        # Non-hapax exact/graphic-match shortcut (gated by --llm-shortcuts).
        # A graphic-only difference (hyphen/case/accent) is normalised to
        # CONFORME here: the metric scores terminological choice, not orthography.
        if level in ("exact", "graphic") and args.llm_shortcuts in ("non_hapax", "non_hapax_and_vedette"):
            annotations.append(OccurrenceAnnotation(verdict="CONFORME", **common))
            continue

        # Aligned pair fields used in prompts (raw alignment) + canonical forms
        # (used internally for the divergence comparison). source_term: surface
        # form (case preserved) for display, matching the segment and the raw target.
        src_form_raw = r.get("source_term") or src_raw
        tgt_aligned_raw = tgt_aligned_raw_val
        src_canonical = src_raw
        tgt_canonical = tgt

        # divergence -> Q1
        q1_code = "NO"
        q1_justif = ""
        q1_propagated = False
        q1_source_seg = ""
        if args.q1_mode == "llm" and not args.dry_run and llm is not None:
            # --propagate-q1: a single call per group of identical occurrences,
            # carried by the designated occurrence. All the blocks of the prompt
            # are rebuilt from THAT occurrence (see _q1_call), so the reused
            # verdict is exactly the one it would have produced.
            _pkey = propagation_key(r) if _prop_on else None
            _rep = _prop_rep.get(_pkey) if _pkey is not None else None
            if _rep is not None and len(_prop_groups.get(_pkey, ())) > 1:
                if _pkey not in _q1_memo:
                    _q1_memo[_pkey] = _q1_call(records[_rep], _rep)
                q1 = _q1_memo[_pkey]
                if _rep != idx:
                    q1_propagated = True
                    _rep_seg = (records[_rep].get("source_segment_ids") or [None])[0]
                    q1_source_seg = f"seg{_rep_seg}" if _rep_seg is not None else "?"
            else:
                q1 = _q1_call(r, idx)
            q1_code = q1.code
            q1_justif = q1.justification

        if q1_code in Q1_GRAVITY:
            annotations.append(OccurrenceAnnotation(
                verdict=q1_code, q1_code=q1_code, q1_justification=q1_justif,
                q1_propagated=q1_propagated, q1_source_seg=q1_source_seg, **common,
            ))
            continue

        other_refs = other_form_references(ckey, src_norm, references)
        head = io_records.head_term(r)
        q2 = q2_qualify(
            target_canonical=tgt,
            reference=ref_choice.reference,
            src_term=r.get("source_term", src_raw),
            src_form_raw=src_form_raw,
            tgt_aligned_raw=tgt_aligned_raw,
            src_canonical=src_canonical,
            src_segment=r.get("source_segment", ""),
            tgt_segment=r.get("target_segment", ""),
            variation_category=common["variation_category"],
            other_form_references=other_refs,
            glossary_entry=glossary_entry,
            is_first_mention=is_first,
            concept_history=history,
            context_window=ctx_window,
            use_llm=(not args.dry_run and args.q2_mode == "llm" and llm is not None),
            llm=llm,
            llm_prompt_tmpl=prompts.get("q2_vartj"),
            dump_label=make_dump_label(system, r),
            concept_renderings=build_concept_renderings(records, idx, io_records.raw_target),
            context_pairs=ctx_pairs,
            head_or_variant=(
                "" if not head else
                ("head term" if (r.get("source_term") or "").strip().lower() == head.lower()
                 else "variant")
            ),
        )
        annotations.append(OccurrenceAnnotation(
            verdict=q2.code,
            q1_code=q1_code,
            q1_justification=q1_justif,
            q1_propagated=q1_propagated,
            q1_source_seg=q1_source_seg,
            q2_reason=q2.reason,
            q2_justification=q2.justification,
            **common,
        ))
    gen_traces = [rc.generation_trace for rc in references.values() if rc.generation_trace]
    return annotations, gen_traces


def _write_run_manifest(run_dir: Path, args) -> None:
    """Write a JSON manifest with the full configuration of this run."""
    import json as _json
    import datetime as _dt
    run_dir.mkdir(parents=True, exist_ok=True)
    meta = {
        "run_tag": args.run_tag,
        "written_at": _dt.datetime.now().isoformat(timespec="seconds"),
        "params": {
            "input_dir": str(args.input_dir),
            "systems": args.systems,
            "glossary": str(args.glossary) if args.glossary else None,
            "source_docs_dir": str(args.source_docs_dir) if args.source_docs_dir else None,
            "target_docs_dir": str(args.target_docs_dir) if args.target_docs_dir else None,
            "reference_mode": args.reference_mode,
            "generate_scope": args.generate_scope,
            "generate_contexts": args.generate_contexts,
            "generate_retry_temperature": args.generate_retry_temperature,
            "q1_mode": args.q1_mode,
            "domain": args.domain,
            "q2_mode": args.q2_mode,
            "hapax_mode": args.hapax_mode,
            "judge_path": args.judge_path,
            "propagate_q1": args.propagate_q1,
            "propagate_pick": args.propagate_pick,
            "llm_shortcuts": args.llm_shortcuts,
            "context_window": args.context_window,
            "model": args.model,
            "base_url": args.base_url,
            "temperature": args.temperature,
            "max_tokens": args.max_tokens,
            "max_docs": args.max_docs,
            "workers": args.workers,
            "dry_run": args.dry_run,
        },
    }
    with open(run_dir / "run_meta.json", "w", encoding="utf-8") as f:
        _json.dump(meta, f, ensure_ascii=False, indent=2)


def _write_prompts_snapshot(run_dir: Path, prompts: Dict[str, str], args) -> None:
    """Freeze the *resolved* prompt templates actually used by this run.

    ``prompts`` is the dict returned by ``load_prompts`` after ``inject_examples``
    and ``inject_domain`` ran, i.e. the exact text (few-shot block + domain
    substituted) that will be ``str.format``-ed per occurrence. Snapshotting
    makes every run self-documenting about the prompt that produced its
    verdicts. Cheap (five short files), so it always runs.
    """
    snap = run_dir / "prompts_used"
    snap.mkdir(parents=True, exist_ok=True)
    for name, text in prompts.items():
        (snap / f"{name}.txt").write_text(text, encoding="utf-8")
    index = (
        "# Prompts used for this run\n\n"
        f"- domain: `{args.domain or '(none)'}`\n\n"
        "The `.txt` files here are the fully resolved templates (few-shot and "
        "domain blocks already substituted). They are a frozen copy of the "
        "package's `prompts/<name>.txt` at run time; `hapax_judge.txt` is the "
        "text of `q1_classify.txt`.\n"
    )
    (snap / "README.md").write_text(index, encoding="utf-8")


def annotate_system(
    system: str,
    input_dir: Path,
    output_dir: Path,
    args: argparse.Namespace,
    glossary: Optional[Glossary],
    chain: List[str],
    llm: Optional[LLMClient],
    prompts: Dict[str, str],
    context_loader: ContextLoader,
) -> None:
    import sys
    system_dir = input_dir / system
    if not system_dir.is_dir():
        print(f"[WARN] Missing system dir: {system_dir}", file=sys.stderr)
        return
    doc_ids = io_records.list_docs(system_dir)
    if args.max_docs > 0:
        doc_ids = doc_ids[: args.max_docs]
    if not doc_ids:
        print(f"[WARN] No docs for system {system}", file=sys.stderr)
        return

    run_dir = output_dir / system / "runs" / args.run_tag
    out_sys = run_dir / "annotations"
    chains_dir = run_dir / "chains"
    # Write the run manifest and freeze the resolved prompts once at the root
    # of this run folder, so the config is fully recoverable from disk.
    _write_run_manifest(run_dir, args)
    _write_prompts_snapshot(run_dir, prompts, args)
    def _do_doc(doc_id: str) -> None:
        records = io_records.load_doc(system_dir, doc_id, system)
        if not records:
            return
        ds = context_loader.get(doc_id, system)
        io_records.fill_segments(records, ds.src_lines, ds.tgt_lines,
                                 where=str(system_dir / f"{doc_id}.json"))
        items, gen_traces = annotate_doc(
            system=system, doc_id=doc_id, records=records, args=args,
            glossary=glossary, chain=chain, llm=llm, prompts=prompts,
            context_loader=context_loader,
        )
        write_annotations(out_sys / f"{doc_id}.json", items)
        if gen_traces:
            # One JSONL per (system, doc): thread-safe under --workers, and the
            # per-run audit file reviewers read (contexts shown, attempts, status).
            import json as _json
            gd = run_dir / "generated_references"
            gd.mkdir(parents=True, exist_ok=True)
            with open(gd / f"{doc_id}.jsonl", "w", encoding="utf-8") as f:
                for t in gen_traces:
                    f.write(_json.dumps(t, ensure_ascii=False) + "\n")
        if not args.no_chains:
            write_chain_md(
                chains_dir / f"{doc_id}.md",
                items,
                system=system,
                doc_id=doc_id,
                src_lines=ds.src_lines,
                tgt_lines=ds.tgt_lines,
                run_tag=args.run_tag,
                run_params={
                    "reference_mode": args.reference_mode,
                    "q1_mode": args.q1_mode,
                    "q2_mode": args.q2_mode,
                    "hapax_mode": args.hapax_mode,
                    "judge_path": args.judge_path,
                    "llm_shortcuts": args.llm_shortcuts,
                    "context_window": args.context_window,
                    "model": args.model,
                    "workers": args.workers,
                },
            )

    workers = max(1, args.workers)
    if workers > 1:
        # Documents are independent -> process them concurrently. LLM calls are
        # I/O-bound, so threads give a large speedup; the shared LLM cache is
        # lock-protected on write. Keep workers modest to respect rate limits.
        from concurrent.futures import ThreadPoolExecutor, as_completed
        bar = None
        if args.progress:
            try:
                from tqdm import tqdm as _tqdm_bar
                bar = _tqdm_bar(total=len(doc_ids), desc=f"{system} (x{workers})", unit="doc", leave=True)
            except ImportError:
                bar = None
        with ThreadPoolExecutor(max_workers=workers) as ex:
            futures = [ex.submit(_do_doc, d) for d in doc_ids]
            for fut in as_completed(futures):
                fut.result()  # surface any per-doc exception
                if bar is not None:
                    bar.update(1)
        if bar is not None:
            bar.close()
    else:
        docs_iter = _maybe_tqdm(
            doc_ids,
            enabled=args.progress,
            desc=f"{system}",
            unit="doc",
            leave=True,
        )
        for doc_id in docs_iter:
            if hasattr(docs_iter, "set_postfix_str"):
                docs_iter.set_postfix_str(f"{doc_id}")
            _do_doc(doc_id)

    print(f"[OK] {system}: {len(doc_ids)} docs annotated -> {out_sys}")
    if not args.no_chains:
        print(f"[OK] {system}: chain views -> {chains_dir}")

    # Explicit post-run verification of the "generate" strategy: count what was
    # generated / declined / failed (with fallback) from the persisted traces.
    gd = run_dir / "generated_references"
    if "generate" in chain and gd.is_dir():
        import json as _json
        from collections import Counter
        stat: Counter = Counter()
        n_total = 0
        for p in sorted(gd.glob("*.jsonl")):
            for line in open(p, encoding="utf-8"):
                try:
                    t = _json.loads(line)
                except Exception:
                    continue
                n_total += 1
                stat[t.get("status", "?")] += 1
        detail = ", ".join(f"{k}={v}" for k, v in sorted(stat.items())) or "none"
        print(f"[GENERATE] {system}: {n_total} generation attempt(s) ({detail}) -> {gd}")


def run(args: argparse.Namespace) -> None:
    input_dir = args.input_dir.resolve()
    if not input_dir.is_dir():
        raise SystemExit(f"Input dir not found: {input_dir}")

    output_dir = args.output_dir
    output_dir.mkdir(parents=True, exist_ok=True)
    if not args.run_tag:
        args.run_tag = build_run_tag(args)
    print(f"[INFO] Run tag: {args.run_tag}")

    # ``--save-prompts auto`` is a sentinel: dump every raw LLM prompt/response
    # under a per-run folder so heavy dumps from different configs never mix.
    # Filenames already carry system+doc+seg (see make_dump_label), so a single
    # folder per run_tag is unambiguous even across systems.
    if args.save_prompts is not None and str(args.save_prompts) == "auto":
        args.save_prompts = output_dir / "_prompt_dumps" / args.run_tag

    glossary: Optional[Glossary] = None
    if args.glossary is not None:
        print(f"[INFO] Loading glossary: {args.glossary}")
        glossary = Glossary(args.glossary)
        print(f"[INFO] Glossary entries: {len(glossary)}")
    else:
        print("[INFO] No glossary: references come from the documents and the LLM only")

    chain = parse_mode(args.reference_mode)
    print(f"[INFO] Reference chain: {chain}")

    prompts = inject_domain(inject_examples(load_prompts()), args.domain)
    if args.domain:
        print(f"[INFO] Domain injected into the prompts: {args.domain}")

    llm: Optional[LLMClient] = None
    needs_llm = (
        ("llm" in chain) or ("generate" in chain) or ("validated" in chain)
        or (args.q1_mode == "llm") or (args.q2_mode == "llm")
    )
    if needs_llm and not args.dry_run:
        cache_dir = args.cache_dir or (output_dir / "cache" / args.model.replace("/", "_"))
        llm = LLMClient(
            LLMConfig(
                model=args.model,
                base_url=args.base_url,
                api_key=args.api_key,
                temperature=args.temperature,
                max_tokens=args.max_tokens,
                save_prompts_dir=args.save_prompts,
            ),
            cache_dir=cache_dir,
        )
        print(f"[INFO] LLM ready: model={args.model} endpoint={args.base_url or '(OpenAI API)'} cache={cache_dir}")
        if args.save_prompts is not None:
            print(f"[INFO] Saving LLM prompts/responses under {args.save_prompts}")

    if args.context_window > 0 and (args.source_docs_dir is None or args.target_docs_dir is None):
        raise SystemExit(
            "--context-window > 0 requires both --source-docs-dir (<doc_id>.txt files) and "
            "--target-docs-dir (<SYSTEM>/<doc_id>.txt files), one segment per line."
        )
    # The loader is always built: besides the context window, the document
    # texts fill missing segments in the records and head the chain views.
    context_loader = ContextLoader(args.source_docs_dir, args.target_docs_dir)

    systems_all = io_records.list_systems(input_dir)
    systems = [s.strip() for s in args.systems.split(",") if s.strip()] if args.systems.strip() else systems_all
    missing = [s for s in systems if s not in systems_all]
    if missing:
        raise SystemExit(f"Unknown system(s) under {input_dir}: {missing} (available: {systems_all})")
    if not systems:
        raise SystemExit(f"No systems to process under {input_dir}")

    print(f"[INFO] Systems to process: {systems}")
    for system in systems:
        annotate_system(
            system=system, input_dir=input_dir, output_dir=output_dir,
            args=args, glossary=glossary, chain=chain, llm=llm, prompts=prompts,
            context_loader=context_loader,
        )

    _report_token_usage(llm, output_dir, args)


def _report_token_usage(llm, output_dir, args) -> None:
    """Print + persist the token usage of ACTUAL API calls for this run.

    Records, per prompt, input/output tokens, the largest completion seen (to
    tune --max-tokens) and how many calls were TRUNCATED (finish_reason=length
    -> JSON unparseable -> silent default). Optionally estimates cost from
    --price-in / --price-out (USD per 1M tokens).
    """
    if llm is None:
        return
    summ = llm.usage_summary()
    tot = summ["totals"]
    if not tot["calls"]:
        return
    print(f"\n[TOKENS] run={args.run_tag} model={summ['model']} max_tokens={summ['max_tokens']}")
    print(f"[TOKENS] {'prompt':16s} {'calls':>7s} {'in_tok':>10s} {'out_tok':>10s} {'max_in':>8s} {'max_out':>8s} {'trunc':>6s}")
    for name, u in sorted(summ["by_prompt"].items()):
        print(f"[TOKENS] {name:16s} {u['calls']:7d} {u['prompt_tokens']:10d} "
              f"{u['completion_tokens']:10d} {u.get('max_prompt_tokens', 0):8d} "
              f"{u['max_completion_tokens']:8d} {u['truncated']:6d}")
    print(f"[TOKENS] {'TOTAL':16s} {tot['calls']:7d} {tot['prompt_tokens']:10d} "
          f"{tot['completion_tokens']:10d} {'':8s} {'':8s} {tot['truncated']:6d}")
    if tot.get("length_retries"):
        print(f"[TOKENS] {tot['length_retries']} call(s) hit the cap and were retried "
              f"with a larger budget (max_tokens doubled).")
    hard = tot.get("hard_truncated", 0)
    if hard:
        print(f"[TOKENS][WARN] {hard} call(s) STILL truncated after retries "
              f"(finish_reason=length) => silent default verdict. RAISE --max-tokens "
              f"(largest completion seen: "
              f"{max((u['max_completion_tokens'] for u in summ['by_prompt'].values()), default=0)}).")
    price_in = args.price_in
    price_out = args.price_out
    cost = None
    if price_in is not None or price_out is not None:
        cost = (tot["prompt_tokens"] / 1e6) * (price_in or 0.0) + \
               (tot["completion_tokens"] / 1e6) * (price_out or 0.0)
        print(f"[TOKENS] estimated cost (API calls only, cache hits free): "
              f"${cost:.4f}  (in={price_in}/1M, out={price_out}/1M)")
    try:
        import json as _json
        out = output_dir / f"_token_usage__{args.run_tag}.json"
        payload = dict(summ)
        payload["run_tag"] = args.run_tag
        if cost is not None:
            payload["estimated_cost_usd"] = round(cost, 6)
            payload["price_in_per_1M"] = price_in
            payload["price_out_per_1M"] = price_out
        out.write_text(_json.dumps(payload, indent=2), encoding="utf-8")
        print(f"[TOKENS] usage written to {out}")
    except Exception:
        pass


def main(argv: Optional[List[str]] = None) -> None:
    """Entry point for the ``termjudge-annotate`` console script."""
    run(parse_args(argv))


if __name__ == "__main__":
    main()
